const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

function resolveVersion() {
  // 1. Explicit environment variable (from CI/CD workflow)
  if (process.env.APP_VERSION) {
    return process.env.APP_VERSION.replace(/^v/, '').trim();
  }

  // 2. Try git tags (local development with git)
  try {
    const latestTag = execSync('git tag -l "v[0-9]*.[0-9]*.[0-9]*" --sort=-v:refname', {
      encoding: 'utf-8',
      stdio: ['pipe', 'pipe', 'ignore']
    }).trim().split('\n')[0];

    if (latestTag && latestTag.startsWith('v')) {
      return latestTag.replace(/^v/, '').trim();
    }
  } catch (e) {
    // Git not available or no tags found
  }

  // 3. Fallback to package.json version
  try {
    const pkgPath = path.join(__dirname, '..', 'package.json');
    if (fs.existsSync(pkgPath)) {
      const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8'));
      if (pkg.version && pkg.version !== '0.0.0') {
        return pkg.version.replace(/^v/, '').trim();
      }
    }
  } catch (e) {}

  // 4. Default fallback
  return '1.0.0';
}

const version = resolveVersion();
const environmentsDir = path.join(__dirname, '..', 'src', 'environments');
const targetFile = path.join(environmentsDir, 'version.ts');

if (!fs.existsSync(environmentsDir)) {
  fs.mkdirSync(environmentsDir, { recursive: true });
}

const content = `// Auto-generated by scripts/generate-version.js - DO NOT EDIT MANUALLY
export const APP_VERSION = '${version}';
`;

fs.writeFileSync(targetFile, content, 'utf-8');
console.log(`[generate-version] Generated version file with version v${version}`);

